"""Emit the C data of one cacophony vector: python3 -I gen_noise_kat.py <cacophony.txt> <protocol_name> <prefix>

The handshake bytes come from the vector as they are. The two leading keys of the masked
form are computed here from the mask construction of the engine, which no vector covers:
mask = HMAC-BLAKE2s(HMAC-BLAKE2s(psk, "duct handshake mask"), message id || last 16 bytes of the message),
the message id being 1 for the first handshake message and 2 for the second.

The messages are listed in a table of vector_msg_t and the vector as a whole is one vector_t named after
the prefix; every header defines both types once under a shared guard.
"""
import hashlib
import hmac
import json
import sys

path, name, prefix = sys.argv[1], sys.argv[2], sys.argv[3]
with open(path, encoding="utf-8") as f:
    doc = json.load(f)
v = next(x for x in doc["vectors"] if x["protocol_name"] == name)

# Messages of the handshake itself; the rest of the vector is transport data.
HANDSHAKE_MESSAGES = {"IKpsk2": 2, "XKpsk3": 3}
pattern = name.split("_")[1]


def arr(cname, data):
    rows = [
        "    " + " ".join("0x%02x," % c for c in data[i:i + 12])
        for i in range(0, len(data), 12)
    ]
    return "static const uint8_t %s_%s[%d] = {\n%s\n};\n" % (prefix, cname, len(data), "\n".join(rows))


def hx(key):
    return bytes.fromhex(v[key])


psk = bytes.fromhex(v["init_psks"][0])
assert psk == bytes.fromhex(v["resp_psks"][0])
assert v["init_prologue"] == v["resp_prologue"]
msgs = [(bytes.fromhex(m["payload"]), bytes.fromhex(m["ciphertext"])) for m in v["messages"]]

out = ["/* %s, cacophony vectors/cacophony.txt. Generated by gen_noise_kat.py. */\n" % name]
out.append(
    "#ifndef NOISE_KAT_VECTOR\n"
    "#define NOISE_KAT_VECTOR\n"
    '#include "duct_noise.h"\n'
    "#include <stddef.h>\n"
    "#include <stdint.h>\n"
    "typedef struct {\n"
    "    const uint8_t *payload,\n"
    "                  *ct;\n"
    "    size_t         payload_len,\n"
    "                   ct_len;\n"
    "} vector_msg_t;\n"
    "typedef struct {\n"
    "    const char           *name;\n"
    "    duct_noise_pattern_t  pattern;\n"
    "    unsigned              handshake_messages,\n"
    "                          messages;\n"
    "    const uint8_t        *prologue;\n"
    "    size_t                prologue_len;\n"
    "    const uint8_t        *psk,\n"
    "                         *init_static,\n"
    "                         *init_ephemeral,\n"
    "                         *resp_static,\n"
    "                         *resp_ephemeral,\n"
    "                         *resp_static_pub,\n"
    "                         *handshake_hash,\n"
    "                         *masked_head[2];\n"
    "    const vector_msg_t   *message;\n"
    "} vector_t;\n"
    "#endif\n"
)
out.append(arr("prologue", hx("init_prologue")))
out.append(arr("psk", psk))
out.append(arr("init_static", hx("init_static")))
out.append(arr("init_ephemeral", hx("init_ephemeral")))
out.append(arr("resp_static", hx("resp_static")))
out.append(arr("resp_ephemeral", hx("resp_ephemeral")))
out.append(arr("resp_static_pub", hx("init_remote_static")))
out.append(arr("handshake_hash", hx("handshake_hash")))
for i, (payload, ct) in enumerate(msgs):
    out.append(arr("payload%d" % i, payload))
    out.append(arr("ct%d" % i, ct))

key = hmac.new(psk, b"duct handshake mask", hashlib.blake2s).digest()
for i in (0, 1):
    ct = msgs[i][1]
    mask = hmac.new(key, bytes([i + 1]) + ct[-16:], hashlib.blake2s).digest()
    out.append(arr("masked_head%d" % i, bytes(a ^ b for a, b in zip(ct[:32], mask))))
out.append("static constexpr unsigned %s_messages = %d;\n" % (prefix, len(msgs)))
rows = [
    "    { %s_payload%d, %s_ct%d, sizeof %s_payload%d, sizeof %s_ct%d }," % ((prefix, i) * 4)
    for i in range(len(msgs))
]
out.append("static const vector_msg_t %s_message[%s_messages] = {\n%s\n};\n" % (prefix, prefix, "\n".join(rows)))
fields = [
    ("name", '"%s"' % name),
    ("pattern", "noise_pattern_%s" % pattern.lower()),
    ("handshake_messages", "%d" % HANDSHAKE_MESSAGES[pattern]),
    ("messages", "%s_messages" % prefix),
    ("prologue", "%s_prologue" % prefix),
    ("prologue_len", "sizeof %s_prologue" % prefix),
    ("psk", "%s_psk" % prefix),
    ("init_static", "%s_init_static" % prefix),
    ("init_ephemeral", "%s_init_ephemeral" % prefix),
    ("resp_static", "%s_resp_static" % prefix),
    ("resp_ephemeral", "%s_resp_ephemeral" % prefix),
    ("resp_static_pub", "%s_resp_static_pub" % prefix),
    ("handshake_hash", "%s_handshake_hash" % prefix),
    ("masked_head", "{ %s_masked_head0, %s_masked_head1 }" % (prefix, prefix)),
    ("message", "%s_message" % prefix),
]
out.append("static const vector_t %s = {\n%s\n};\n" % (prefix, "\n".join("    .%s = %s," % f for f in fields)))
sys.stdout.write("\n".join(out))
